import requests

OLLAMA_URL = "http://localhost:11434/api/generate"
OLLAMA_MODEL = "llama3.2"


def explain_prediction(housing_data, predicted_price):
    """
    Generate a plain-language explanation of a house price prediction.
    Sends the housing features and the predicted median house value
    to a locally running Ollama language model.

    Args:
        housing_data (dict): Housing features submitted by the user.
        predicted_price (float): The predicted median house value expressed in US dollars.

    Returns:
        str:Explanation generated by Ollama.

    Raises:
        requests.RequestException: If the HTTP request fails, times out, or receives an unsuccessful HTTP status.
        KeyError: If the JSON response does not contain the expected "response" field.
        ValueError: If the response cannot be decoded as JSON.
    """
    prompt = f"""
    You are explaining a California housing price prediction
    to someone without a technical background.

    User-provided Housing features:
    {housing_data}

    Predicted median house value: ${predicted_price:,.2f}

    Explain the prediction in simple language in 3 to 5 sentences.
    Discuss how the housing features might relate to
    the estimated value.Explain more above the predicted price. 
    Mention that income and geographic location can influence estimates.

    Do not claim to know the exact reasons behind
    the machine learning model's prediction.
    Keep the explanation short and clear.
    """

    response = requests.post(
        OLLAMA_URL,
        json={
            "model": OLLAMA_MODEL,
            "prompt": prompt,
            "stream": False,
        },
        timeout=90,
    )
    # change this to raise an exception if the request fails
    response.raise_for_status()
    #  response is in json format , convert the response to dict and return the "response" field
    return response.json()["response"]
