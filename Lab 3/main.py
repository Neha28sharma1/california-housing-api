# Load the Model Once When the App Starts and Store It in the App State
@asynccontextmanager
async def lifespan(app: FastAPI):
    """
    Manage application startup and shutdown.

    Startup:
        Load the pretrained housing model and store it in
        app.state.predictor.

    Shutdown:
        Clear the predictor reference when the app stops.
    """
    print("Loading Hugging Face model...")
    # stores model state in the app's state object, which can be accessed when handling requests instead of loading the model for each request
    app.state.predictor = load_housing_model()
    print("Model loaded successfully!")

    yield

    app.state.predictor = None


# 2.1 Create FastAPI application
app = FastAPI(
    title="California Housing Price Prediction API",
    description="Predict median housing values using a pretrained Hugging Face XGBoost model.",
    version="1.0.0",
    lifespan=lifespan,
)

# 2.3 Implement POST /predict
@app.post("/predict", response_model=PredictionResponse)
def predict_house_price(
    housing: HousingInput,
    request: Request,):
    """
    Predict a house price from the submitted housing features.

    Args:
        housing: Validated housing features supplied by the user.
        request: The current FastAPI request, used to access
                 the model stored in the application state.

    Returns:
        PredictionResponse: The predicted house price in USD.
    """
    # Convert user input into a dictionary
    input_data = housing.model_dump()

    # Use the pretrained model
    predictor = request.app.state.predictor
    result = predictor.predict(input_data)

    # 2.5 Return the predicted price as JSON
    return PredictionResponse(
        predicted_price_usd=float(result["price_usd"]),
    )


# response model and endpoint for prediction explanation
class ExplanationResponse(BaseModel):
    """
    Define the response containing the predicted price
    and its text generated by Ollama.
    """
    predicted_price_usd: float
    explanation: str


@app.post(
    "/prediction_explanation",
    response_model=ExplanationResponse,
)
def prediction_explanation(
    housing: HousingInput,
    request: Request,
):
    """
    Predict a house price and explain the result using Ollama.

    Args:
        housing: Validated housing features supplied by the user.
        request: The current FastAPI request.

    Returns:
        ExplanationResponse: The predicted price and explanation.

    Raises:
        HTTPException 500: If the housing prediction fails.
        HTTPException 503: If the explanation service is unavailable.
    """
    try:
        # Get the housing inputs
        # Convert validated Pydantic input into a dictionary
        input_data = housing.model_dump()

        # Predict using the Hugging Face model

        predictor = request.app.state.predictor
        result = predictor.predict(input_data)

        predicted_price = float(result["price_usd"])

    except Exception as exc:
        raise HTTPException(
            status_code=500,
            detail="Unable to generate a housing price prediction.",
        ) from exc

    try:
        # Ask Ollama to explain the prediction
        explanation = explain_prediction(
            input_data,
            predicted_price,
        )
    # Handle Ollama connection errors
    except requests.RequestException as exc:
        raise HTTPException(
            status_code=503,
            detail=(
                  f"The predicted price is ${predicted_price:,.2f}, "
                  "but the explanation service is unavailable. "
                  "Please try again later."
              )
        ) from exc
    # Return the final responses
    return ExplanationResponse(
        predicted_price_usd=predicted_price,
        explanation=explanation,
    )
